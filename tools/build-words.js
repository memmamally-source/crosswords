#!/usr/bin/env node
// Builds js/words.js from the word lists in words/*.txt.
// Each list has one entry per line: ANSWER | clue   (lines starting with # are comments)
// Run after editing a list:  node tools/build-words.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'words');

function readLists() {
  const lists = {};
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.txt')).sort()) {
    const id = file.replace(/\.txt$/, '');
    const entries = [];
    fs.readFileSync(path.join(dir, file), 'utf8').split('\n').forEach((raw, i) => {
      const line = raw.trim();
      if (!line || line.startsWith('#')) return;
      const bar = line.indexOf('|');
      if (bar < 0) throw new Error(`${file}:${i + 1}: expected "ANSWER | clue"`);
      const answer = line.slice(0, bar).trim().toUpperCase().replace(/[^A-Z]/g, '');
      const clue = line.slice(bar + 1).trim();
      if (!answer || !clue) throw new Error(`${file}:${i + 1}: empty answer or clue`);
      entries.push(`${answer}|${clue}`);
    });
    lists[id] = entries.join('\n');
  }
  return lists;
}

function render(lists) {
  return [
    '// Generated by tools/build-words.js from words/*.txt. Do not edit by hand.',
    `var CROSSWORD_WORDS = ${JSON.stringify(lists, null, 0)};`,
    "if (typeof module !== 'undefined' && module.exports) module.exports = CROSSWORD_WORDS;",
    '',
  ].join('\n');
}

const out = path.join(root, 'js', 'words.js');
const text = render(readLists());
if (require.main === module) {
  fs.writeFileSync(out, text);
  console.log(`Wrote ${path.relative(root, out)}`);
}
module.exports = { readLists, render, out };
